CREATE OR REPLACE FUNCTION protect_room_type_business_code()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.code IS DISTINCT FROM NEW.code
       AND (
           EXISTS (
               SELECT 1
               FROM reservation_room_types
               WHERE room_type_id = OLD.id
           )
           OR EXISTS (
               SELECT 1
               FROM room_rate_profiles
               WHERE room_type_id = OLD.id
           )
       ) THEN
        RAISE EXCEPTION
            'room_types.code is immutable after financial or reservation use'
            USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_room_types_protect_business_code
BEFORE UPDATE OF code ON room_types
FOR EACH ROW
EXECUTE FUNCTION protect_room_type_business_code();
