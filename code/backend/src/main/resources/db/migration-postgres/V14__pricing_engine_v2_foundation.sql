CREATE OR REPLACE FUNCTION protect_room_type_capacity()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.max_guests < OLD.max_guests
       AND EXISTS (
           SELECT 1
           FROM room_rate_profiles
           WHERE room_type_id = OLD.id
             AND active = true
             AND included_guests > NEW.max_guests
       ) THEN
        RAISE EXCEPTION
            'room_types.max_guests cannot be lower than active included guests'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_room_types_protect_capacity
BEFORE UPDATE OF max_guests ON room_types
FOR EACH ROW
EXECUTE FUNCTION protect_room_type_capacity();

