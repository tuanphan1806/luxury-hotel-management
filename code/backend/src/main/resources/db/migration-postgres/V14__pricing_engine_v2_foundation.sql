    line_guest_count integer NOT NULL,
    room_quantity integer NOT NULL,
    extra_guest_count integer NOT NULL,
    first_block_minutes integer NOT NULL,
    first_block_price decimal(14,2) NOT NULL,
    extra_unit_minutes integer NOT NULL,
    extra_unit_price decimal(14,2) NOT NULL,
