    overnight_included_checkout timestamp(6) without time zone,
    daily_price decimal(14,2) NOT NULL,
    daily_duration_minutes integer NOT NULL,
    full_days integer NOT NULL,
    remainder_minutes integer NOT NULL,
    charged_extra_units integer NOT NULL,
    minimum_committed_room_charge decimal(14,2) NOT NULL,
    final_room_charge decimal(14,2) NOT NULL,
    extra_guest_charge decimal(14,2) NOT NULL,
    allocated_service_charge decimal(14,2) NOT NULL,
    adjustment_amount decimal(14,2) NOT NULL,
    breakdown_json jsonb NOT NULL,
    snapshot_hash char(64) NOT NULL,
    created_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT uk_reservation_rate_snapshot_sequence
        UNIQUE (reservation_room_type_id, snapshot_sequence),
    CONSTRAINT fk_rate_snapshot_reservation_room_type
        FOREIGN KEY (reservation_room_type_id) REFERENCES reservation_room_types(id),
    CONSTRAINT fk_rate_snapshot_policy
        FOREIGN KEY (stay_policy_version_id) REFERENCES stay_policy_versions(id),
    CONSTRAINT fk_rate_snapshot_profile
        FOREIGN KEY (rate_profile_id) REFERENCES room_rate_profiles(id),
    CONSTRAINT chk_rate_snapshot_stage
        CHECK (snapshot_stage IN (
            'COMMITMENT', 'CHECK_IN', 'EXTENSION', 'CHECKOUT', 'ADJUSTMENT')),
    CONSTRAINT chk_rate_snapshot_algorithm
        CHECK (pricing_algorithm_version = 'MOTEL_PACKAGE_V2'),
    CONSTRAINT chk_rate_snapshot_classification
        CHECK (stay_classification IN ('DAY_STAY', 'NIGHT_STAY', 'MULTI_DAY')),
    CONSTRAINT chk_rate_snapshot_packages
        CHECK (initial_package IN ('HOURLY', 'OVERNIGHT', 'DAILY')
            AND applied_package IN ('HOURLY', 'OVERNIGHT', 'DAILY')
            AND max_package_reached IN ('HOURLY', 'OVERNIGHT', 'DAILY')),
    CONSTRAINT chk_rate_snapshot_transition
        CHECK (transition_reason IN (
            'INITIAL_QUOTE', 'HOURLY_WINDOW', 'OVERNIGHT_WINDOW',
            'DAILY_DURATION', 'PRICE_CAP', 'EXTENSION',
            'ACTUAL_CHECKOUT', 'ADMIN_APPROVED_ADJUSTMENT')),
    CONSTRAINT chk_rate_snapshot_interval
        CHECK (committed_check_out > committed_check_in
            AND (actual_check_out IS NULL OR actual_check_in IS NULL
                OR actual_check_out > actual_check_in)),
    CONSTRAINT chk_rate_snapshot_guest_counts
        CHECK (included_guests >= 1
            AND max_guests_snapshot >= included_guests
            AND line_guest_count >= 0
            AND room_quantity >= 1
            AND line_guest_count <= max_guests_snapshot * room_quantity
            AND extra_guest_count >= 0),
    CONSTRAINT chk_rate_snapshot_units
        CHECK (first_block_minutes >= 1
            AND extra_unit_minutes >= 1
            AND grace_minutes >= 0
            AND daily_duration_minutes >= 60
            AND full_days >= 0
            AND remainder_minutes >= 0
            AND charged_extra_units >= 0),
    CONSTRAINT chk_rate_snapshot_amounts
        CHECK (first_block_price >= 0
            AND extra_unit_price >= 0
            AND overnight_price >= 0
            AND daily_price >= 0
            AND minimum_committed_room_charge >= 0
            AND final_room_charge >= 0
            AND extra_guest_charge >= 0
            AND allocated_service_charge >= 0)
);

