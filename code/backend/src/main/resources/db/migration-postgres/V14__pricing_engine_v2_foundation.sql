ALTER TABLE room_types
    ADD COLUMN code varchar(40);

DO $$
BEGIN
    IF EXISTS (
        WITH canonical AS (
            SELECT CASE
                WHEN lower(trim(coalesce(type_name_en, ''))) = 'standard'
                  OR lower(trim(coalesce(type_name, ''))) = 'phòng tiêu chuẩn'
                    THEN 'STANDARD'
                WHEN lower(trim(coalesce(type_name_en, ''))) = 'deluxe'
                  OR lower(trim(coalesce(type_name, ''))) = 'phòng deluxe'
                    THEN 'DELUXE'
                WHEN lower(trim(coalesce(type_name_en, ''))) = 'executive room'
                  OR lower(trim(coalesce(type_name, ''))) = 'phòng executive'
                    THEN 'EXECUTIVE'
                WHEN lower(trim(coalesce(type_name_en, ''))) = 'suite'
                  OR lower(trim(coalesce(type_name, ''))) = 'phòng suite'
                    THEN 'SUITE'
                WHEN lower(trim(coalesce(type_name_en, ''))) = 'family room'
                  OR lower(trim(coalesce(type_name, ''))) = 'phòng gia đình'
                    THEN 'FAMILY'
                WHEN lower(trim(coalesce(type_name_en, ''))) = 'presidential suite'
                  OR lower(trim(coalesce(type_name, ''))) = 'phòng tổng thống'
                    THEN 'PRESIDENTIAL'
                ELSE NULL
            END AS code
            FROM room_types
        )
        SELECT 1
        FROM canonical
        WHERE code IS NOT NULL
        GROUP BY code
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Pricing V2 preflight failed: duplicate canonical room type';
    END IF;
END;
$$;

