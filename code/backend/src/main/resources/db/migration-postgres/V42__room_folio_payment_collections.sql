CREATE TABLE room_folio_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    selection JSONB NOT NULL,
    closed_at TIMESTAMP
);
CREATE UNIQUE INDEX uq_room_folio_collection_open ON room_folio_collections(reservation_id) WHERE closed_at IS NULL;
ALTER TABLE payment_transactions ADD COLUMN room_folio_collection_id BIGINT REFERENCES room_folio_collections(id);
CREATE INDEX idx_payment_room_folio_collection ON payment_transactions(room_folio_collection_id) WHERE room_folio_collection_id IS NOT NULL;
ALTER TABLE reservation_room_departures ADD COLUMN qr_collected BIGINT NOT NULL DEFAULT 0
    CHECK (qr_collected >= 0 AND qr_collected + cash_collected <= allocated_payment);
